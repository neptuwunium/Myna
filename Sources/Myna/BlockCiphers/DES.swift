import Foundation

public struct DES: BlockCipher {
	public var blockSize: Int = 8

	private var key: DESKeySchedule

	@inline(__always)
	private static func permute(_ a: inout UInt32, _ b: inout UInt32, _ t: inout UInt32, _ n: Int, _ mod: UInt32) {
		t = ((a >> n) ^ b) & mod
		b ^= t
		a ^= t << n
	}

	private static func permute(_ a: inout UInt32, _ t: inout UInt32, _ n: Int, _ mod: UInt32) {
		t = ((a << (16 - n)) ^ a) & mod
		a = a ^ t ^ (t >> (16 - n))
	}

	public init(key: DESKey) {
		self.key = DESKeySchedule(repeating: DESKeyLine(repeating: 0))
		var c = UInt32.from(array: key)
		var d = UInt32.from(array: key, offset: 4)
		var t: UInt32 = 0

		Self.permute(&d, &c, &t, 4, 0x0f0f_0f0f)
		Self.permute(&c, &t, -2, 0xcccc_0000)
		Self.permute(&d, &t, -2, 0xcccc_0000)
		Self.permute(&d, &c, &t, 1, 0x5555_5555)
		Self.permute(&c, &d, &t, 8, 0x00ff_00ff)
		Self.permute(&d, &c, &t, 1, 0x5555_5555)
		d = (((d & 0x0000_00ff) << 16) | (d & 0x0000_ff00) | ((d & 0x00ff_0000) >> 16) | ((c & 0xf000_0000) >> 4))
		c &= 0x0fff_ffff

		for i in 1 ... 16 {
			if keyShift[i - 1] {
				c = ((c >> 2) | (c << 26))
				d = ((d >> 2) | (d << 26))
			} else {
				c = ((c >> 1) | (c << 27))
				d = ((d >> 1) | (d << 27))
			}

			c &= 0x0fff_ffff
			d &= 0x0fff_ffff

			// the analyzer has issues with this block so i separated it as much as i could
			// it still struggles.

			let c20 = (c >> 20) & 0x01
			let c21 = (c >> 21) & 0x06
			let c22 = (c >> 22) & 0x38
			let s1 = UInt32(keyBits[0][Int(c & 0x3f)])
			let s2 = UInt32(keyBits[1][Int(((c >> 6) & 0x03) | ((c >> 7) & 0x3c))])
			let s3 = UInt32(keyBits[2][Int(((c >> 13) & 0x0f) | ((c >> 14) & 0x30))])
			let s4 = UInt32(keyBits[3][Int(c20 | c21 | c22)])

			let k0 = s1 | s2 | s3 | s4

			let t1 = UInt32(keyBits[4][Int(d & 0x3f)])
			let t2 = UInt32(keyBits[5][Int(((d >> 7) & 0x03) | ((d >> 8) & 0x3c))])
			let t3 = UInt32(keyBits[6][Int((d >> 15) & 0x3f)])
			let t4 = UInt32(keyBits[7][Int(((d >> 21) & 0x0f) | ((d >> 22) & 0x30))])

			let k1 = t1 | t2 | t3 | t4

			let k2 = ((k1 << 16) | (k0 & 0x0000_ffff)) & 0xffff_ffff
			self.key[i - 1][0] = k2.rotate(right: 30) & 0xffff_ffff

			let k3 = ((k0 >> 16) | (k1 & 0xffff_0000))
			self.key[i - 1][1] = k3.rotate(right: 26) & 0xffff_ffff
		}
	}

	public func encrypt(_ plainText: Data) throws -> Data {
		throw MynaError.notImplemented
	}

	public func decrypt(_ cipherText: Data) throws -> Data {
		throw MynaError.notImplemented
	}
}

