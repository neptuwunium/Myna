import Foundation
import Testing

@testable import Myna

struct CBCTests {
	@Test func roundTripTest() async throws {
		let algorithm = XTEA(key: [0x10, 0x40, 0x80, 0xff])
		let stimulus: Data = Data(repeating: 0x42, count: algorithm.blockSize * 4)
		let cbc = CBCTransform(algorithm: algorithm, iv: nil, paddingMode: NoPadding())
		let encrypted = try cbc.encrypt(stimulus)
		let decrypted = try cbc.decrypt(encrypted)
		#expect(decrypted.elementsEqual(stimulus))
	}

	@Test func roundTripPaddingTest() async throws {
		let algorithm = XTEA(key: [0x10, 0x40, 0x80, 0xff])
		let stimulus: Data = Data(repeating: 0x42, count: algorithm.blockSize * 4)
		let cbc = CBCTransform(algorithm: algorithm, iv: nil, paddingMode: PKCS7Padding())
		let encrypted = try cbc.encrypt(stimulus)
		let decrypted = try cbc.decrypt(encrypted)
		#expect(decrypted.elementsEqual(stimulus))
	}

	@Test func encryptTest() async throws {
		let algorithm = XTEA(key: [0x10, 0x40, 0x80, 0xff])
		let cbc = CBCTransform(algorithm: algorithm, iv: nil, paddingMode: NoPadding())
		let encrypted = try cbc.encrypt(Data(repeating: 0x42, count: algorithm.blockSize * 4))
		let reference = Data([
			0x90, 0x76, 0xab, 0xe3, 0x36, 0x1f, 0x25, 0x19,
			0xaf, 0x29, 0xe4, 0x17, 0x5b, 0x75, 0x4a, 0x8e,
			0xf1, 0x46, 0xec, 0x55, 0x1a, 0x27, 0x6b, 0xbb,
			0x67, 0xa4, 0xf9, 0xe7, 0x8d, 0xaf, 0xdd, 0xa6,
		])
		#expect(encrypted.elementsEqual(reference))
	}

	@Test func decryptTest() async throws {
