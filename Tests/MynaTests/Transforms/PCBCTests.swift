		let encrypted = try pcbc.encrypt(Data(repeating: 0x42, count: algorithm.blockSize * 4))
		let reference = Data([
			0x90, 0x76, 0xab, 0xe3, 0x36, 0x1f, 0x25, 0x19,
			0xec, 0xb2, 0x17, 0x2c, 0x00, 0xc0, 0x09, 0x8b,
